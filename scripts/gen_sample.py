def main():
    vas, chars, works = {}, {}, {}
    casts, appearances, series = {}, [], []
    work = None

    def src(title):
        return [{"source": "manual", "url": "https://ja.wikipedia.org/wiki/" + title.replace(" ", "_"), "fetchedAt": FETCHED}]

    def va_id(name):
        if name not in vas:
            v = {"id": f"va:sample-{len(vas) + 1:03d}", "name": name}
            if name in READINGS:
                v["reading"] = READINGS[name]
            v["wikipediaTitle"] = name
            v["sources"] = src(name)
            vas[name] = v
        return vas[name]["id"]

    for line in TABLE.strip().splitlines():
        cols = line.split("|")
        if cols[0] == "W":
            _, title, fmt, year, pop, ser, *rest = cols
            work = {
                "id": f"wk:sample-{len(works) + 1:03d}", "title": title, "format": fmt,
                "year": int(year), "series": ser, "popularity": int(pop) * 1000, "sources": src(title),
            }
            works[title] = work
            for r in rest:
                series.append({"from": works[r[1:]]["id"], "to": work["id"], "relation": "SEQUEL"})
            continue
        name, role, cast = cols
        if name not in chars:
            chars[name] = {"id": f"ch:sample-{len(chars) + 1:03d}", "name": name, "sources": work["sources"]}
        ch = chars[name]["id"]
        appearances.append({"character": ch, "work": work["id"], "role": "MAIN" if role == "M" else "SUPPORTING"})
        medium = "game" if work["format"] == "GAME" else "anime"
        for entry in cast.split(","):
            vname, *extra = entry.split(":")
            row = {"voiceActor": va_id(vname), "character": ch, "medium": medium}
            if extra:
                row["kind"] = extra[0]
                start, _, end = extra[1].partition("-")
                row["period"] = {k: int(v) for k, v in (("from", start), ("to", end)) if v}
                row["work"] = work["id"]
            casts.setdefault((row["voiceActor"], ch, medium), row)

    # 仮のお気に入り数: サンプル内の役数に比例させる
    counts = {}
    for (va, _, _) in casts:
        counts[va] = counts.get(va, 0) + 1
    for v in vas.values():
        v["favourites"] = counts[v["id"]] * 1000

    out = pathlib.Path(__file__).resolve().parent.parent / "data" / "sample"
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "voice_actors": list(vas.values()), "characters": list(chars.values()), "works": list(works.values()),
        "casts": list(casts.values()), "appearances": appearances, "series": series,
    }
    for name, rows in files.items():
        text = "[\n" + ",\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n]\n"
        (out / f"{name}.json").write_text(text, encoding="utf-8")
        print(f"{name}: {len(rows)}")


if __name__ == "__main__":
    main()
